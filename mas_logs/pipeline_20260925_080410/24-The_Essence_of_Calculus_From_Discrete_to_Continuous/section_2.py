class Section2Scene(TeachingScene):
    def construct(self):
        self.setup_layout("The Power of Zooming In", ["Zooming into a curve reveals its path.", "Small segments eventually look like straight lines.", "This is our window to local analysis."])
        
        # Mobjects
        curve = FunctionGraph(lambda x: 0.5 * x**2 + 0.1 * x**3, x_range=[-2, 2], color=BLUE)
        self.place_in_area(curve, 'A3', 'F6', scale_factor=0.4)
        self.add(curve)
        
        segment_label = Text("Straight line", font_size=20, color=RED)
        self.place_at_grid(segment_label, 'C4', scale_factor=0.6)
        segment_label.set_opacity(0)
        self.add(segment_label)
        
        # === Animation for Lecture Line 1 ===
        self.play(self.lecture[0].animate.set_color(YELLOW))
        # Zooming animation logic using camera frame
        self.play(self.camera.frame.animate.set_width(4).move_to(curve.point_from_proportion(0.5)))

        # === Animation for Lecture Line 2 ===
        self.play(self.lecture[1].animate.set_color(YELLOW))
        # Represent zooming in further
        self.play(self.camera.frame.animate.set_width(1.5).move_to(curve.point_from_proportion(0.5)))
        line = Line(start=curve.point_from_proportion(0.48), end=curve.point_from_proportion(0.52), color=RED)
        self.play(Create(line))
        self.play(segment_label.animate.set_opacity(1))

        # === Animation for Lecture Line 3 ===
        self.play(self.lecture[2].animate.set_color(YELLOW))
        self.wait(1)
